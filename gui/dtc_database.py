def decode_dtc_code(code: str) -> str:
    """Look up a DTC code and return its description."""
    code = code.upper().strip()
    if code in DTC_DATABASE:
        return DTC_DATABASE[code]
    prefix = code[:1] if code else ""
    prefix_map = {
        "P": "动力系统",
        "C": "底盘系统",
        "B": "车身系统",
        "U": "通信系统",
    }
    category = prefix_map.get(prefix, "未知类别")
    return f"{category}故障 (无已知描述)"
